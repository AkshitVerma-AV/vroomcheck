if page == "Emerging defects":
    st.header("Which failure patterns are rising abnormally with no recall yet?")
    status = st.segmented_control("Status", ["EMERGING", "RECALLED", "WATCH", "NON-DEFECT"], default="EMERGING")
    alerts = cached("list_alerts", status, None, 300)
    makes = ["(all)"] + sorted(alerts.make.unique().tolist())
    mk = st.selectbox("Make", makes)
    view = alerts if mk == "(all)" else alerts[alerts.make == mk]
    st.dataframe(view[["cluster_id", "make", "model", "min_model_year", "max_model_year", "size",
                       "top_component", "keywords", "n_crash", "n_fire", "n_injured", "first_spike_month",
                       "last_spike_month", "matched_campno", "priority"]],
                 use_container_width=True, hide_index=True, height=300)
    if not view.empty:
        cid = st.selectbox("Inspect cluster", view.cluster_id.tolist())
        c = cached("get_cluster", cid)
        a, b, d, e = st.columns(4)
        a.metric("Complaints", int(c["size"]))
        b.metric("Crashes / fires", f"{int(c['n_crash'])} / {int(c['n_fire'])}")
        d.metric("Injuries / deaths", f"{int(c['n_injured'])} / {int(c['n_deaths'])}")
        e.metric("Status", c["status"])
        st.markdown(f"**Keywords:** {c['keywords']}  ·  **Component:** {c['top_component']} "
                    f"({c['component_purity']:.0%} of complaints)  ·  **Model years:** "
                    f"{c['min_model_year']}–{c['max_model_year']}")
        st.plotly_chart(spike_chart(cid, c.get("matched_recall_date")), use_container_width=True)
        left, right = st.columns([3, 2])
        with left:
            st.subheader("Representative complaints")
            comp = cached("cluster_complaints", cid)
            for r in comp.itertuples():
                flags = " ".join(x for x, f in [("💥crash", r.is_crash), ("🔥fire", r.is_fire),
                                                 (f"🚑{r.injured} injured", r.injured)] if f)
                with st.expander(f"C-{r.odino} · MY{r.model_year} · {r.received_date:%Y-%m-%d} {flags}"):
                    st.write(r.narrative)
        with right:
            st.subheader("Most similar past recalls (RAG)")
            sim = q.similar_recalls(q.cluster_centroid(cid), k=5)
            st.dataframe(sim[["campno", "recall_date", "makes", "component_tops", "similarity"]],
                         hide_index=True, use_container_width=True)
        st.subheader("AI defect brief")
        brief = q.load_brief(cid)
        if st.button("Generate / refresh brief with agents", type="primary"):
            from vroomcheck.agents.graph import generate_brief
            with st.spinner("signal → retrieval → drafting → verifier ..."):
                brief = generate_brief(cid)
        if brief:
            show_brief(brief)
        else:
            st.caption("No brief yet for this cluster.")

elif page == "Check a vehicle (VIN)":
    st.header("For this VIN, what recalls apply and what are owners reporting?")
    vin = st.text_input("VIN (17 characters)", "5YJ3E1EA7KF000000")
    if st.button("Check", type="primary"):
        with st.spinner("decoding VIN with NHTSA vPIC ..."):
            r = q.vin_check(vin)
        if "error" in r:
            st.error(r["error"]); st.json(r["vehicle"])
        else:
            v = r["vehicle"]
            st.subheader(f"{v['model_year']} {v['make']} {v['model']}  ·  {v.get('body_class') or ''}")
            a, b, c = st.columns(3)
            a.metric("Official recalls (warehouse)", len(r["recalls"]))
            b.metric("Official recalls (live NHTSA API)", r["live_recall_count"])
            c.metric("Unrecalled complaint patterns", len(r["unrecalled_patterns"]))
            st.markdown("#### Official recalls")
            st.dataframe(r["recalls"], hide_index=True, use_container_width=True)
            st.markdown("#### What other owners report that is *not* covered by a recall")
            st.dataframe(r["unrecalled_patterns"], hide_index=True, use_container_width=True)
            st.markdown("#### Complaints for this exact model year, by component")
            st.bar_chart(r["complaints_by_component"].set_index("component")["complaints"].head(12))

