# ------------------------------------------------------------------ helpers
def spike_chart(cid: str, recall_date=None):
    m = cached("cluster_monthly", cid)
    fig = go.Figure()
    fig.add_bar(x=m.month, y=m.n, name="complaints / month", marker_color="#8aa4c8")
    fig.add_scatter(x=m.month, y=m.expected_3m / 3, name="expected (baseline x fleet growth)",
                    line=dict(color="#555", dash="dot"))
    sp = m[m.is_spike]
    fig.add_scatter(x=sp.month, y=sp.n, mode="markers", name="spike flagged",
                    marker=dict(color="#d62728", size=9, symbol="triangle-up"))
    if recall_date is not None and pd.notna(recall_date):
        fig.add_vline(x=pd.Timestamp(recall_date), line_color="#2ca02c", line_width=2)
        fig.add_annotation(x=pd.Timestamp(recall_date), y=1, yref="paper", text="recall", showarrow=False,
                           font=dict(color="#2ca02c"))
    fig.update_layout(height=320, margin=dict(l=10, r=10, t=10, b=10), legend=dict(orientation="h", y=1.12))
    return fig


def show_brief(brief: dict):
    st.markdown(f"### {brief.get('title')}")
    c1, c2, c3 = st.columns(3)
    c1.metric("Risk level", brief.get("risk_level") or "-")
    c2.metric("Verified claims", len(brief.get("claims", [])))
    c3.metric("Rejected by verifier", len(brief.get("rejected_claims", [])))
    st.write(brief.get("summary"))
    ev = brief.get("evidence", {})
    for cl in brief.get("claims", []):
        st.markdown(f"- {cl['text']}  \n  <small>evidence: {', '.join(f'`{c}`' for c in cl['citations'])}</small>",
                    unsafe_allow_html=True)
    if brief.get("recommended_action"):
        st.info(f"**Recommended action:** {brief['recommended_action']}")
    if brief.get("rejected_claims"):
        with st.expander("Claims rejected by the verifier agent"):
            for r in brief["rejected_claims"]:
                st.markdown(f"- ~~{r['text']}~~ — *{r['reason']}*")
    with st.expander(f"Evidence pack ({len(ev)} documents)"):
        st.dataframe(pd.DataFrame([{"id": k, **{kk: vv for kk, vv in v.items() if kk != 'text'},
                                    "text": v.get("text", "")[:200]} for k, v in ev.items()]),
                     use_container_width=True, hide_index=True)
    with st.expander("Agent trace"):
        st.code("\n".join(brief.get("trace", [])))
    st.caption(f"generated by {brief.get('generated_by')} at {brief.get('generated_at')}")


