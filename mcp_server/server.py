"""Vroomcheck MCP server: exposes the warehouse and agents as tools any MCP
client (desktop assistants, IDEs, agents) can call.

Run:  python -m mcp_server.server            (stdio transport)
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from mcp.server.mcpserver import MCPServer  # noqa: E402  (mcp >= 2; FastMCP in 1.x)

from vroomcheck.services import queries as q  # noqa: E402

mcp = MCPServer("vroomcheck")


def _records(df, cols=None, n=None):
    if cols:
        df = df[[c for c in cols if c in df.columns]]
    if n:
        df = df.head(n)
    return df.astype(object).where(df.notna(), None).to_dict(orient="records")


@mcp.tool()
def list_emerging_defects(make: str | None = None, limit: int = 10) -> list[dict]:
    """Competency Q1: failure patterns rising abnormally fast with no matching recall,
    ranked by priority (volume x spike strength x harm x component severity)."""
    df = q.list_alerts("EMERGING", make=make, limit=limit)
    return _records(df, ["cluster_id", "make", "model", "min_model_year", "max_model_year", "size",
                         "top_component", "keywords", "n_crash", "n_fire", "n_injured", "n_deaths",
                         "first_spike_month", "last_spike_month", "recent_max_ratio", "priority"])


@mcp.tool()
def get_defect_brief(cluster_id: str, regenerate: bool = False) -> dict:
    """Return the verified defect brief for a cluster (generated by the agent graph if missing).
    Every claim cites complaint (C-), recall (R-), bulletin (T-) or investigation (I-) IDs."""
    brief = None if regenerate else q.load_brief(cluster_id)
    if brief is None:
        from vroomcheck.agents.graph import generate_brief

        brief = generate_brief(cluster_id)
    return {k: v for k, v in brief.items() if k != "evidence"}


@mcp.tool()
def check_vin(vin: str) -> dict:
    """Competency Q2: decode a VIN (NHTSA vPIC), list official recalls for that vehicle and
    complaint patterns owners report that are not covered by a recall."""
    r = q.vin_check(vin)
    if "error" in r:
        return r
    return {"vehicle": r["vehicle"], "live_recall_count": r["live_recall_count"],
            "recalls": _records(r["recalls"], ["campno", "recall_date", "component_tops", "defect_summary",
                                               "do_not_drive", "park_outside"]),
            "unrecalled_patterns": _records(r["unrecalled_patterns"]),
            "complaints_by_component": _records(r["complaints_by_component"], n=10)}


@mcp.tool()
def similar_past_recalls(cluster_id: str, k: int = 5) -> list[dict]:
    """Competency Q3: past recalls (any manufacturer) most similar to a complaint cluster."""
    df = q.similar_recalls(q.cluster_centroid(cluster_id), k=k)
    return _records(df, ["campno", "recall_date", "makes", "component_tops", "similarity", "defect_summary"])


@mcp.tool()
def backtest_summary() -> dict:
    """Competency Q4: how early would Vroomcheck have flagged past recalls?"""
    return {k: (float(v) if v is not None else None) for k, v in q.backtest_summary().items()}


@mcp.tool()
def search_complaints(query: str, make: str | None = None, model: str | None = None, k: int = 10) -> list[dict]:
    """Semantic search over owner complaint narratives."""
    return _records(q.search_complaints(query, make, model, k))


if __name__ == "__main__":
    mcp.run()
